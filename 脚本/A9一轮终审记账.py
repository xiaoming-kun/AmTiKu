def main() -> int:
    claims = {}
    for p in sorted((DIR / "批次").glob("agent[RST].jsonl")):
        for ln in p.read_text(encoding="utf-8").splitlines():
            if not ln.strip():
                continue
            r = json.loads(ln)
            if r.get("verdict") == "错":
                claims[r["key"]] = r
    print("批次里 agent 判「错」的：", len(claims))

    rows, missing = [], []
    # ⚠️ 尾串必须**唯一**命中一道题。早先按序号记账错过 3 条别的题，
    #    按子串记也一样——"数学试卷#12" 能同时命中 "#120"。
    amb = {t: [k for k in claims if t in k] for t in MINE}
    bad = {t: v for t, v in amb.items() if len(v) != 1}
    if bad:
        for t, v in bad.items():
            print(f"!! 尾串 {t!r} 命中 {len(v)} 道：{v}")
        return 1
    for key, c in claims.items():
        why = None
        for tail, note in MINE.items():
            if tail in key:
                why = note
                break
        if why is None:
            missing.append(key)
            continue
        rows.append({"key": key, "result": "pass", "note": "我独立复算：" + why,
                     "at": "2026-10-04"})
    if missing:
        print("!! 这些 key 我没写复算依据，先不落：")
        for m in missing:
            print("   ", m)
        return 1
    with (DIR / "终审.jsonl").open("a", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"已记 {len(rows)} 条 pass")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
