    bad = []
    for p in points:
        seen, lst = set(), []
        for nid in CORE[p] + area_extra(p) + SEC.get(p, []):
            if nid not in ids:
                bad.append((p, nid))
                continue
            if nid not in seen:
                seen.add(nid)
                lst.append(nid)
        out[p] = lst
    if bad:
        print("节点 id 写错了：")
        for p, nid in bad:
            print("  ", p, nid)
        return 1

    doc = {
        "version": 1,
        "updated": datetime.now().strftime("%Y-%m-%d"),
        "how": ("讲解节点逐条手填（CORE），题型/易错按板块规则补（area_extra），"
                "二级结论按对得上补（SEC）；生成脚本见 git 历史"),
        "points": out,
    }
    dst = klist.MAPFILE
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(json.dumps(doc, ensure_ascii=False, indent=1),
                   encoding="utf-8")
    rep = klist.map_report()
    print("写了 %s：%d 个考点" % (dst.name, len(out)))
    print("覆盖 %d/%d，缺 %s" % (rep["points_mapped"], rep["points_total"],
                                 rep["points_missing"] or "无"))
    print("悬空节点 %s，未知考点 %s" % (rep["dangling_nodes"] or "无",
                                       rep["unknown_points"] or "无"))
    orphans = rep["nodes_orphan"]
    idx = klist.index()
    # 只报**自己带正文**的孤儿：光一个标题、内容都在孩子身上的节点不算缺口
    holes = [o for o in orphans if idx[o]["chars"] >= 80]
    print("被引用的节点 %d/%d，孤儿 %d 个（纯标题 %d／带正文 %d）：%s"
          % (rep["nodes_used"], rep["nodes_total"], len(orphans),
             len(orphans) - len(holes), len(holes),
             [(h, idx[h]["chars"]) for h in holes[:10]] or "无"))
    avg = sum(len(v) for v in out.values()) / len(out)
    print("平均每考点挂 %.1f 个节点" % avg)
    return 0


